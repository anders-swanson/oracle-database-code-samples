create table authors (
    id         number(19) generated by default as identity primary key,
    name       varchar2(100 char) not null,
    biography  varchar2(800 char)
);

create table publishers (
    id            number(19) generated by default as identity primary key,
    name          varchar2(120 char) not null,
    country_code  varchar2(2 char)
);

create table books (
    id            number(19) generated by default as identity primary key,
    isbn          varchar2(13 char) not null,
    title         varchar2(200 char) not null,
    publisher_id  number(19),
    constraint fk_books_publisher foreign key (publisher_id) references publishers(id),
    constraint books_isbn_uq unique (isbn)
);

create index idx_books_publisher_id on books(publisher_id);

create table book_authors (
    book_id    number(19),
    author_id  number(19),
    primary key (book_id, author_id),
    constraint fk_book_authors_book foreign key (book_id) references books(id),
    constraint fk_book_authors_author foreign key (author_id) references authors(id)
);

create index idx_book_authors_author_id on book_authors(author_id);

create table book_relations (
    id         number generated always as identity primary key,
    source_id  number(19) not null references books(id),
    target_id  number(19) not null references books(id),
    constraint book_relations_uq unique (source_id, target_id),
    constraint book_relations_self_ck check (source_id <> target_id)
);

create index book_relations_target_ix on book_relations(target_id);

create property graph book_graph
vertex tables (
    books
        key (id)
        label book
        properties (id, title)
)
edge tables (
    book_relations
        key (id)
        source key (source_id) references books(id)
        destination key (target_id) references books(id)
        label related
        properties (id)
);

create table bookstores (
    id        number(19) generated by default as identity primary key,
    name      varchar2(120 char) not null,
    location  mdsys.sdo_geometry not null
);

