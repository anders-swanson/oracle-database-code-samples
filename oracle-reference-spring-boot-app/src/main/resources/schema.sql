create index bookstores_location_ix on bookstores(location)
indextype is mdsys.spatial_index_v2;

create table store_stock (
    id        number generated always as identity primary key,
    store_id  number(19) not null references bookstores(id),
    book_id   number(19) not null references books(id),
    quantity  number(10) not null,
    version   number(19) default 0 not null,
    constraint store_stock_uq unique (store_id, book_id),
    constraint store_stock_quantity_ck check (quantity between 0 and 1000000)
);

create index store_stock_book_ix on store_stock(book_id);

create table stock_adjustments (
    id                  number generated always as identity,
    stock_id            number(19) not null,
    delta               number(10) not null,
    resulting_quantity  number(10) not null,
    recorded_at         timestamp(6) with time zone default systimestamp not null,
    constraint stock_adjustments_pk primary key (id),
    constraint stock_adjustments_stock_fk foreign key (stock_id) references store_stock(id),
    constraint stock_adjustments_delta_ck check (delta <> 0)
);

create index stock_adjustments_stock_ix on stock_adjustments(stock_id);

create table book_embeddings (
    book_id    number(19) primary key references books(id),
    synopsis   varchar2(2000 char) not null,
    embedding  vector(384, FLOAT32)
);

create json relational duality view book_documents_dv as
books {
    _id : id
    isbn
    title
    authors : book_authors [ {
        authors @unnest {
            _id : id
            name
            biography
        }
    } ]
    publisher : publishers {
        _id : id
        name
        countryCode : country_code
    }
    availability : store_stock [ {
        _id : id
        quantity
        version
        store : bookstores {
            _id : id
            name
        }
    } ]
};
